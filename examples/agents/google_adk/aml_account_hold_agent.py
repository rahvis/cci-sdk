def observed_patterns(alert: dict[str, Any]) -> list[str]:
    """What the scripted investigator notices: patterns present or close to a threshold."""
    act, customer = alert["activity_30d"], alert["customer"]
    seen = []
    if act["cash_deposits_8000_to_9999"] >= 2:
        seen.append(f"{act['cash_deposits_8000_to_9999']} cash deposits between 8,000 and 9,999 USD")
    if act["sent_out_within_48h_pct"] >= 75 and act["deposits_total_usd"] >= 20_000:
        seen.append(f"{act['sent_out_within_48h_pct']}% of deposits sent out within 48 hours")
    if act["wires_to_high_risk_jurisdictions_usd"] >= 15_000:
        seen.append(f"{act['wires_to_high_risk_jurisdictions_usd']:,} USD wired to high-risk jurisdictions")
    ratio = act["deposits_total_usd"] / max(customer["expected_monthly_deposits_usd"], 1)
    if ratio > 2.5 and act["deposits_total_usd"] >= 10_000:
        seen.append(f"deposits {ratio:.0f} times the expected monthly profile")
    return seen


def investigator_policy(history: Sequence[types.Content]) -> types.Part:
    """The scripted agent: read the alert, propose a hold when a pattern shows, report the outcome."""
    result = adk_models.last_tool_result(history)
    if result is None:
        match = re.search(r"\bA-\d{4}\b", adk_models.last_user_text(history))
        if not match:
            return adk_models.say("Which alert should I investigate?")
        return adk_models.call("get_alert", alert_id=match.group(0))
    name, response = result
    if name == "get_alert":
        if "error" in response:
            return adk_models.say(response["error"])
        patterns = observed_patterns(response)
        if not patterns:
            return adk_models.say(f"Alert {response['alert_id']} shows no red-flag pattern; I recommend closing it.")
        return adk_models.call("place_account_hold", account_id=response["account_id"],
                               alert_id=response["alert_id"], reason="; ".join(patterns) + ".")
    status = response.get("status")
    if status == "hold_placed":
        return adk_models.say(f"Placed hold {response['hold_id']} on {response['account_id']} for alert "
                              f"{response['alert_id']}.")
    if status == "rejected_by_reviewer":
        return adk_models.say("An analyst declined the hold, so none was placed. I have not retried it; "
                              "the alert stays with the analyst.")
    return adk_models.say(response.get("message") or f"The hold did not go ahead ({status}).")


def _uniform(*parts: Any) -> float:
    digest = hashlib.sha256(json.dumps(parts).encode()).digest()
    return int.from_bytes(digest[:8], "big") / 2**64


def _sigmoid(x: float) -> float:
    return 1.0 / (1.0 + math.exp(-max(-60.0, min(60.0, x))))


def mock_hold_evidence(context: Any, instructions: Any, options: Any) -> dict[str, float]:
    """A fallible reader of the alert facts, standing in for an LLM's P(hold warranted).

    It scores the guideline's patterns softly (so values near a threshold
    are uncertain), over-trusts verified documentation a little even for
    structuring, and adds deterministic noise keyed on the alert id. It sees
    only the context; the calibration label is never passed to it.
    """
    alert = context["alert"]
    act, customer, doc = alert["activity_30d"], alert["customer"], alert["documentation"]["status"]
    s = _sigmoid((act["cash_deposits_8000_to_9999"] - 2.5) * 2.4)
    v = _sigmoid((act["sent_out_within_48h_pct"] - 79.5) / 2.5) * _sigmoid((act["deposits_total_usd"] - 25_000) / 2_500)
    j = _sigmoid((act["wires_to_high_risk_jurisdictions_usd"] - 20_000) / 2_000)
    ratio = act["deposits_total_usd"] / max(customer["expected_monthly_deposits_usd"], 1)
    p = _sigmoid((ratio - 3.0) / 0.3) * _sigmoid((act["deposits_total_usd"] - 10_000) / 1_500)
    others = v + j + p
    logit = -2.4 + 4.4 * s * (0.8 if doc == "verified" else 1.0)
    logit += {"none": 2.8, "partial": 1.1, "verified": 0.3}[doc] * others
    if doc == "partial":
        logit += 1.8 * max(0.0, others - 1.0)
    logit += 0.15 * min(alert["prior_alerts_12m"], 3)
    logit += (_uniform("aml", alert["alert_id"], 1) + _uniform("aml", alert["alert_id"], 2) - 1.0) * 1.8
    p_true = _sigmoid(logit)
    return {"true": p_true, "false": 1.0 - p_true}


