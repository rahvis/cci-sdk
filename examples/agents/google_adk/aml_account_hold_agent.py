class CaseSystem:
    """Stand-in for the case-management and core-banking systems."""

    def __init__(self, alerts: Sequence[dict[str, Any]]) -> None:
        self.alerts = {a["alert_id"]: a for a in alerts}
        self.holds: list[dict[str, Any]] = []

    def hold_context(self, args: dict[str, Any]) -> dict[str, Any]:
        """The guard's context for a proposed hold: the case facts, rendered like the calibration set.

        A hold on an unknown alert, or on an account that is not the alert's,
        raises here; the guard then escalates instead of guessing.
        """
        alert = self.alerts.get(args.get("alert_id"))
        if alert is None:
            raise ValueError(f"alert {args.get('alert_id')!r} is not in the case system")
        if args.get("account_id") != alert["account_id"]:
            raise ValueError(f"account {args.get('account_id')!r} is not the account on alert {alert['alert_id']}")
        return alert_context(alert)


def make_tools(cases: CaseSystem):
    def get_alert(alert_id: str) -> dict:
        """Read an AML alert: customer profile, 30-day activity, documentation and prior alerts.

        Args:
            alert_id: The alert identifier, for example "A-5001".
        """
        alert = cases.alerts.get(alert_id)
        return alert_context(alert)["alert"] if alert else {"error": f"no alert {alert_id}"}

    def place_account_hold(account_id: str, alert_id: str, reason: str) -> dict:
        """Place a temporary hold on an account under investigation.

        Args:
            account_id: The account to hold, as shown on the alert.
            alert_id: The alert that justifies the hold.
            reason: One sentence naming the red-flag patterns observed.
        """
        hold = {"hold_id": f"HOLD-{alert_id}", "account_id": account_id, "alert_id": alert_id, "reason": reason}
        cases.holds.append(hold)
        return {"status": "hold_placed", **hold}

    return get_alert, place_account_hold


