def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    providers.add_arguments(parser)
    parser.add_argument("--batch", action="store_true",
                        help=f"decide a nightly queue of {NIGHTLY_SIZE} alerts with gate_batch instead")
    return parser


async def run_scenarios(client: LocalCLIClient, model: Any, reviewer: Reviewer) -> dict[str, Any]:
    cases = CaseSystem(SCENARIO_ALERTS)
    guard = ToolGuard(client, [
        GuardRule(tool="place_account_hold", query=HOLD_GATE, context=cases.hold_context),
    ])
    agent = Agent(name="aml_investigator", model=model, instruction=INSTRUCTION,
                  tools=list(make_tools(cases)))
    # App-wide: the plugin guards place_account_hold for every agent the runner drives.
    app = App(name=APP, root_agent=agent, plugins=[CLIGuardPlugin(guard)])
    sessions = InMemorySessionService()
    runner = Runner(app=app, session_service=sessions)
    outcomes: dict[str, Any] = {}
    try:
        for case_id, headline in SCENARIOS:
            display.scenario(case_id, headline)
            session = await sessions.create_session(app_name=APP, user_id=USER)
            holds_before = len(cases.holds)
            ask = f"Investigate alert {case_id} and place a hold if the guideline calls for one."
            events = await adk_models.run_turn(runner, user_id=USER, session_id=session.id,
                                               message=adk_models.user_message(ask))
            adk_models.print_turn(events, ran_status="hold_placed")
            reviewed: Optional[bool] = None
            for request in confirmation_requests(events):
                reviewed = reviewer.decide(case_id, request)
                answer = {"reviewer": "aml-analyst", "decision": "approved" if reviewed else "rejected"}
                events = await adk_models.run_turn(runner, user_id=USER, session_id=session.id,
                                                   message=confirmation_response(request["id"], reviewed, answer))
                adk_models.print_turn(events, ran_status="hold_placed")
            state = (await sessions.get_session(app_name=APP, user_id=USER, session_id=session.id)).state
            audit = [entry["action"] for entry in state.get(AUDIT_KEY, [])]
            print(f"    audit: session.state[{AUDIT_KEY!r}] = {audit}")
            outcomes[case_id] = {"action": audit[0] if audit else None, "reviewed": reviewed,
                                 "executed": len(cases.holds) > holds_before, "audit": audit,
                                 "final_text": adk_models.final_text(events)}
    finally:
        await runner.close()
    return {"scenarios": outcomes, "holds": cases.holds}


def run_batch(client: LocalCLIClient) -> dict[str, Any]:
    """Nightly mode: decide a whole queue with conformal selection + Benjamini-Hochberg."""
    queue = generate(NIGHTLY_SIZE, seed=NIGHTLY_SEED, first_id=7001)
    answers = client.gate_batch([row["context"] for row in queue], HOLD_GATE)
    held = [row for row, answer in zip(queue, answers) if answer.approved]
    unwarranted = sum(1 for row in held if not row["label"])
    warranted = sum(1 for row in queue if row["label"])
    statement = answers[0].guarantee.describe()

    def para(text: str, first: str = "    ", rest: str = "    ") -> None:
        print(textwrap.fill(text, 78, initial_indent=first, subsequent_indent=rest))

    print("-" * 78)
    para(f"Nightly queue: {NIGHTLY_SIZE} synthetic alerts from the calibration set's generator (so "
         "exchangeable with it), decided together with client.gate_batch().", "", "")
    print(f"    auto-held:        {len(held)}")
    para(" ".join(row["id"] for row in held), " " * 22, " " * 22)
    print(f"    sent to analysts: {NIGHTLY_SIZE - len(held)}")
    para(statement, "    guarantee: ", " " * 15)
    para(f"demo check, possible only because the labels are synthetic: {unwarranted} of the {len(held)} "
         f"automatic holds {'was' if unwarranted == 1 else 'were'} unwarranted, and {len(held) - unwarranted} "
         f"of the {warranted} warranted holds in the queue were placed automatically (the rest wait for an "
         "analyst). The bound is on the expected fraction across batches, so one batch can land above or "
         "below it.")
    return {"batch": {"size": NIGHTLY_SIZE, "auto_held": [row["id"] for row in held],
                      "escalated": [row["id"] for row, a in zip(queue, answers) if not a.approved],
                      "unwarranted_auto_holds": unwarranted, "statement": statement}}


def run(argv: Optional[Sequence[str]] = None, *, reviewer: Optional[Reviewer] = None) -> dict[str, Any]:
    """Run the demo and return what happened (used by the tests)."""
    args = build_parser().parse_args(argv)
    evidence_provider = args.evidence_provider or args.provider
    # Both models are built before anything else, so a placeholder key stops the run here.
    model = None if args.batch else adk_models.agent_model(args.provider, policy=investigator_policy)
    backend = providers.evidence_backend(evidence_provider, mock_scorer=mock_hold_evidence)
    client = LocalCLIClient(backend, store=calibration.default_store(__file__, args.store),
                            sample_count=providers.sample_count(evidence_provider))

    display.banner("Google ADK: AML account-hold investigator with a calibrated FDR guard", "compliance")
    agent_label = "(not used in --batch)" if args.batch else args.provider
    print(f"agent model: {agent_label}; evidence model: {evidence_provider}")
    already, _ = client.calibration_status(HOLD_GATE)
    sys.stdout.flush()  # calibration progress goes to stderr
    examples = calibration.load_jsonl("aml_alerts.jsonl")
    profile = calibration.ensure_calibrated(client, [HOLD_GATE], examples, recalibrate=args.recalibrate)[0]
    print(f"calibration: data/aml_alerts.jsonl ({len(examples)} synthetic alerts)")
    print(f"profile: {profile.name}, {profile.method}, n={profile.n} (minimum {profile.minimum_n}), "
          f"{profile.status}, {'cached' if already and not args.recalibrate else 'calibrated now'}")

    if args.batch:
        result = run_batch(client)
    else:
        reviewer = reviewer or Reviewer(interactive=args.interactive, script=ANALYST_SCRIPT, role="AML analyst")
        result = asyncio.run(run_scenarios(client, model, reviewer))
    display.footer()
    result["profile"] = {"name": profile.name, "method": profile.method, "n": profile.n, "status": profile.status,
                         "calibrated_now": not already or args.recalibrate}
    return result


def main(argv: Optional[Sequence[str]] = None) -> int:
    run(argv)
    return 0


