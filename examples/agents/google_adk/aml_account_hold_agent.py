"""Google ADK: an AML alert investigator whose account holds pass a calibrated FDR guard.

All data here is synthetic: invented alerts, accounts and a fictional
investigation guideline. Nothing in this example is legal or regulatory
advice.

What the agent does
    A ``google.adk.agents.Agent`` investigates anti-money-laundering alerts.
    It reads an alert with ``get_alert`` (unguarded) and, when it sees a
    red-flag pattern, proposes ``place_account_hold(account_id, alert_id,
    reason)``.

The decision being guarded
    Placing a temporary hold on a customer's account. An unwarranted hold
    freezes an innocent customer's money; a missed one lets funds leave. The
    guard decides each proposed hold before the tool runs.

Primitive and guarantee
    ``Gate(guarantee="fdr", target=0.10, delta=0.10, calibration_profile="aml-holds-v1")``,
    a Learn-then-Test selective threshold. Guarantee, as the SDK states it:
    "With 90% confidence, at most 0.1 of auto-approved decisions are wrong
    (Learn-then-Test, fixed-sequence, n=360)." In words: with 90%
    confidence over the calibration draw, at most 10% of the holds the guard
    places automatically are unwarranted, on alerts like the calibration set.
    It is a bound on a rate across many holds, not a statement that any one
    hold is correct; every hold it does not auto-approve goes to an analyst.

    ``--batch`` decides a nightly queue of 40 alerts at once with
    ``client.gate_batch(contexts, gate)``: conformal selection with
    Benjamini-Hochberg, which bounds the expected fraction of unwarranted
    holds among those auto-held across the batch (finite-sample FDR).

How it plugs into ADK
    ``CLIGuardPlugin(guard)`` is registered on the ``App`` the ``Runner``
    serves, so it guards ``place_account_hold`` for every agent and sub-agent.
    allow: the tool runs. escalate: ADK tool confirmation
    (``adk_request_confirmation``) pauses the turn; the analyst's answer is
    sent back with ``confirmation_response(...)`` on the same session, and
    ADK re-runs the original call only if it was approved. block: the tool
    is skipped and the agent is told why (a Gate never blocks: it approves
    or escalates). Every decision is also written to
    ``session.state["cli_guard_audit"]``.

    The guard evaluates the case facts from the case system, built with the
    same ``alert_context()`` that built the calibration set; the agent's own
    ``reason`` text is never part of the evaluated context.

Data
    ``data/aml_alerts.jsonl``: 360 synthetic alerts with investigator
    decisions, generated by ``data/generate_aml_alerts.py`` (seeded, stdlib
    only). About half warrant a hold.

Run (from sdk/python)
    python examples/agents/google_adk/aml_account_hold_agent.py                # mock: offline, keyless
    python examples/agents/google_adk/aml_account_hold_agent.py --batch        # nightly queue, gate_batch
    python examples/agents/google_adk/aml_account_hold_agent.py --interactive  # you are the analyst

    Real providers read keys from the environment (see examples/agents/.env.example):
    OPENAI_API_KEY=...        python ... --provider openai
    AZURE_OPENAI_API_KEY=...  python ... --provider azure   (also AZURE_OPENAI_ENDPOINT, AZURE_OPENAI_DEPLOYMENT)
    ANTHROPIC_API_KEY=...     python ... --provider anthropic
    GOOGLE_API_KEY=...        python ... --provider gemini

    Gemma 4 on vLLM, as both the agent and the logprob evidence model:
        vllm serve google/gemma-4-12B-it --max-logprobs 20 --generation-config vllm \\
            --enable-auto-tool-choice --tool-call-parser gemma4
        python ... --provider vllm
    Gemma 4 on SGLang:
        python -m sglang.launch_server --model-path google/gemma-4-12B-it --port 30000 \\
            --tool-call-parser gemma4
        python ... --provider sglang
    Mix them, e.g. Claude as the agent and Gemma logprobs as the evidence:
        python ... --provider anthropic --evidence-provider vllm

    Calibration cost: the first run with a real evidence model scores the 360
    alerts once, 360 requests at access level L1 (OpenAI, Azure OpenAI, vLLM,
    SGLang) or 360 x 8 = 2,880 at L0 (Claude, Gemini: 8 samples each), and
    caches the profile in google_adk/.cli_profiles. After that each guarded
    call costs one evidence request (8 at L0); --batch adds 40 (320 at L0).

Expected output (mock)
    A-5001 (structuring): ALLOW, the hold is placed.
    A-5002 (large, documented deposit): ESCALATE, the analyst rejects, no hold.
    A-5003 (just below several thresholds): ESCALATE, the analyst approves, hold placed.
    With --batch: how many of the 40 nightly alerts were auto-held, and the
    batch guarantee. A second run reuses the cached profile and prints the
    same decisions.
"""

