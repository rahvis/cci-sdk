def looks_eligible(record: dict[str, Any]) -> bool:
    """The scripted agent's check: age, diagnosis and labs only. It never reads medications."""
    labs = record["labs_most_recent"]
    return (18 <= record["age_years"] <= 75 and "type 2 diabetes mellitus" in record["diagnoses"]
            and 30 <= labs["egfr_ml_min_1_73m2"] <= 59 and 7.0 <= labs["hba1c_percent"] <= 10.5)


def prescreener_policy(history: Sequence[types.Content]) -> types.Part:
    """The scripted agent: read the record, propose a mark when it looks eligible, report the outcome."""
    result = adk_models.last_tool_result(history)
    patient = re.search(r"\bP-\d{4}\b", adk_models.last_user_text(history))
    patient_id = patient.group(0) if patient else "the patient"
    if result is None:
        if not patient:
            return adk_models.say("Which patient should I pre-screen?")
        return adk_models.call("get_prescreening_record", patient_id=patient_id)
    name, response = result
    if name == "get_prescreening_record":
        if "error" in response:
            return adk_models.say(response["error"])
        if not looks_eligible(response):
            return adk_models.say(f"{patient_id} does not meet the age, diagnosis or lab criteria of {TRIAL_ID}; "
                                  "I have not marked them.")
        return adk_models.call("mark_eligible", patient_id=patient_id, trial_id=TRIAL_ID)
    status = response.get("status")
    if status == "marked_eligible":
        return adk_models.say(f"Marked {patient_id} as pre-screen eligible for {TRIAL_ID}; the study team "
                              "confirms eligibility at the screening visit.")
    if status == "rejected_by_reviewer":
        return adk_models.say(f"The research coordinator declined to mark {patient_id}; I have not retried it.")
    if status == "blocked":
        return adk_models.say(f"I cannot mark {patient_id} as eligible for {TRIAL_ID}: the calibrated check "
                              "blocked it. The record stays in the coordinator's standard screening queue.")
    return adk_models.say(response.get("message") or f"The mark did not go ahead ({status}).")


def _uniform(*parts: Any) -> float:
    digest = hashlib.sha256(json.dumps(parts).encode()).digest()
    return int.from_bytes(digest[:8], "big") / 2**64


def _sigmoid(x: float) -> float:
    return 1.0 / (1.0 + math.exp(-max(-60.0, min(60.0, x))))


def _window(x: float, low: float, high: float, scale: float) -> float:
    return _sigmoid((x - low) / scale) * _sigmoid((high - x) / scale)


def mock_eligibility_evidence(context: Any, instructions: Any, options: Any) -> dict[str, float]:
    """A fallible reader of the record, standing in for an LLM's P(eligible).

    Each criterion is read softly, so labs near a cutoff are uncertain. On
    about 12% of records (chosen by patient id) it slips and overlooks the
    SGLT2 washout and the ALT, pregnancy and study exclusions, the kind of
    confident mistake calibration has to absorb. Deterministic noise is keyed
    on the patient id. It sees only the context, never the label.
    """
    patient = context["patient"]
    labs, pid = patient["labs_most_recent"], patient["patient_id"]
    slip = _uniform("trial-slip", pid) < 0.12
    met = _window(patient["age_years"], 17.5, 75.5, 0.5)
    met *= 0.98 if "type 2 diabetes mellitus" in patient["diagnoses"] else 0.03
    met *= _window(labs["egfr_ml_min_1_73m2"], 29.5, 59.5, 1.6)
    met *= _window(labs["hba1c_percent"], 6.95, 10.55, 0.15)
    if not slip:
        weeks = [m["weeks_since_last_dose"] for m in patient["medications"] if m["drug_class"] == "SGLT2 inhibitor"]
        if weeks:
            met *= _sigmoid((min(weeks) - 12) / 1.2)
        met *= _sigmoid((3.0 - labs["alt_x_uln"]) / 0.2)
        if patient["pregnant_breastfeeding_or_planning"]:
            met *= 0.04
        if patient["interventional_study_last_30_days"]:
            met *= 0.2
    if "type 1 diabetes mellitus" in patient["diagnoses"]:
        met *= 0.05
    if patient["dialysis_or_kidney_transplant"]:
        met *= 0.04
    met = min(max(met, 1e-4), 1 - 1e-4)
    logit = math.log(met / (1 - met)) + (_uniform("trial", pid, 1) + _uniform("trial", pid, 2) - 1.0) * 1.4
    p_true = _sigmoid(logit)
    return {"true": p_true, "false": 1.0 - p_true}


