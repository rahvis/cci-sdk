"""Google ADK: a clinical-trial pre-screening assistant guarded by a Venn-Abers Belief.

All data here is synthetic: invented patients and a fictional protocol,
SYN-CKD-201. This is not medical advice and not a medical device; it must
not be used to decide anyone's care or trial eligibility.

What the agent does
    A ``google.adk.agents.Agent`` reads a pre-screening record with
    ``get_prescreening_record`` (unguarded) and proposes
    ``mark_eligible(patient_id, trial_id)`` when the patient looks eligible.
    The mark is a pre-screening flag: the study team still confirms
    eligibility at the screening visit.

The decision being guarded
    Marking a patient as pre-screen eligible. A wrong mark sends an
    ineligible patient to a screening visit (or past a safety exclusion); the
    guard decides each proposed mark before the tool runs.

Primitive and guarantee
    ``Belief(instructions="Does this patient meet every inclusion criterion
    and no exclusion criterion of the protocol in the context?",
    calibration_profile="trial-screening-v1")`` returns an IVAP (Venn-Abers)
    pair [p0, p1]. The SDK's statement: "Venn-Abers pair [p0, p1]: the
    probability computed under the true label is calibrated on data
    exchangeable with the 320 calibration examples; a wide pair means the
    calibration data cannot pin the probability down." It is not a bracket
    on one patient's true probability. ``GuardRule(allow_above=0.85,
    block_below=0.15)`` maps it:

        interval entirely at or above 0.85   allow: the mark is made
        interval entirely below 0.15         block: the agent is told it cannot mark the patient
        anything else                        escalate: a research coordinator decides

    A Belief is a calibrated probability, not an error-rate bound: it does
    not promise that any one patient is eligible, and it does not cap the
    error rate of automatic marks. It only acts alone where the calibration
    data are unambiguous, on records like the calibration set, and leaves
    the rest to a person. For a stated bound on the rate of wrong automatic
    decisions, use a Gate (see the AML example).

How it plugs into ADK
    ``before_tool_callback=cli_before_tool_callback(guard)`` on this one
    agent. allow: the callback returns None and the tool runs. block: the
    callback returns a result dict, so ADK skips the tool and the model reads
    why. escalate: ``tool_context.request_confirmation(...)`` pauses the turn
    with an ``adk_request_confirmation`` call; the coordinator's answer goes
    back with ``confirmation_response(...)`` on the same session and ADK
    re-runs the original call, which executes only if approved.

    The guard evaluates the record from the screening system, built with the
    same ``screening_context()`` that built the calibration set, never the
    agent's summary of it. A mark for any trial other than SYN-CKD-201 cannot
    be evaluated against this calibration and is escalated.

Data
    ``data/trial_screening.jsonl``: 320 synthetic pre-screening records
    labelled with eligibility at the screening visit, generated by
    ``data/generate_trial_screening.py`` (seeded, stdlib only). Records whose
    labs sit near a cutoff are genuinely uncertain, because the visit
    re-measures them.

Run (from sdk/python)
    python examples/agents/google_adk/clinical_trial_screening_agent.py                # mock: offline, keyless
    python examples/agents/google_adk/clinical_trial_screening_agent.py --interactive  # you are the coordinator

    Real providers read keys from the environment (see examples/agents/.env.example):
    OPENAI_API_KEY=...        python ... --provider openai
    AZURE_OPENAI_API_KEY=...  python ... --provider azure   (also AZURE_OPENAI_ENDPOINT, AZURE_OPENAI_DEPLOYMENT)
    ANTHROPIC_API_KEY=...     python ... --provider anthropic
    GOOGLE_API_KEY=...        python ... --provider gemini

    Gemma 4 on vLLM, as both the agent and the logprob evidence model:
        vllm serve google/gemma-4-12B-it --max-logprobs 20 --generation-config vllm \\
            --enable-auto-tool-choice --tool-call-parser gemma4
        python ... --provider vllm
    Gemma 4 on SGLang:
        python -m sglang.launch_server --model-path google/gemma-4-12B-it --port 30000 \\
            --tool-call-parser gemma4
        python ... --provider sglang

    Calibration cost: the first run with a real evidence model scores the 320
    records once, 320 requests at access level L1 (OpenAI, Azure OpenAI,
    vLLM, SGLang) or 320 x 8 = 2,560 at L0 (Claude, Gemini: 8 samples each),
    and caches the profile in google_adk/.cli_profiles. After that each
    guarded call costs one evidence request (8 at L0).

Expected output (mock)
    P-6001 (clearly eligible): ALLOW, the patient is marked.
    P-6002 (eGFR 59 and HbA1c 10.4%, each at the edge of its range): ESCALATE,
        the coordinator approves, marked.
    P-6003 (SGLT2 inhibitor stopped 5 weeks ago): BLOCK, not marked; the agent says so.
    The scripted agent checks age, diagnosis and labs but, like a hurried
    reader, not medication history, which is why it proposes P-6003 at all.
    A second run reuses the cached profile and prints the same decisions.
"""

