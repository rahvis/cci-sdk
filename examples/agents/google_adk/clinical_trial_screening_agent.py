def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    return providers.add_arguments(parser)


def build_agent(model: Any, guard: ToolGuard, system: ScreeningSystem) -> Agent:
    return Agent(
        name="trial_prescreener",
        model=model,
        instruction=INSTRUCTION,
        tools=list(make_tools(system)),
        before_tool_callback=cli_before_tool_callback(guard),
    )


async def run_scenarios(client: LocalCLIClient, model: Any, reviewer: Reviewer) -> dict[str, Any]:
    system = ScreeningSystem(SCENARIO_RECORDS)
    guard = ToolGuard(client, [
        GuardRule(tool="mark_eligible", query=ELIGIBILITY, context=system.eligibility_context,
                  allow_above=0.85, block_below=0.15),
    ])
    sessions = InMemorySessionService()
    runner = Runner(app=App(name=APP, root_agent=build_agent(model, guard, system)),
                    session_service=sessions)
    outcomes: dict[str, Any] = {}
    try:
        for patient_id, headline in SCENARIOS:
            display.scenario(patient_id, headline)
            session = await sessions.create_session(app_name=APP, user_id=USER)
            marked_before = len(system.marked)
            ask = f"Pre-screen patient {patient_id} for trial {TRIAL_ID}."
            events = await adk_models.run_turn(runner, user_id=USER, session_id=session.id,
                                               message=adk_models.user_message(ask))
            adk_models.print_turn(events, ran_status="marked_eligible")
            reviewed: Optional[bool] = None
            for request in confirmation_requests(events):
                reviewed = reviewer.decide(patient_id, request)
                answer = {"reviewer": "research-coordinator", "decision": "approved" if reviewed else "rejected"}
                events = await adk_models.run_turn(runner, user_id=USER, session_id=session.id,
                                                   message=confirmation_response(request["id"], reviewed, answer))
                adk_models.print_turn(events, ran_status="marked_eligible")
            state = (await sessions.get_session(app_name=APP, user_id=USER, session_id=session.id)).state
            audit = state.get(AUDIT_KEY, [])
            print(f"    audit: session.state[{AUDIT_KEY!r}] = {[entry['action'] for entry in audit]}")
            evidence = (audit[0].get("evidence") or {}) if audit else {}
            outcomes[patient_id] = {"action": audit[0]["action"] if audit else None, "reviewed": reviewed,
                                    "executed": len(system.marked) > marked_before,
                                    "audit": [entry["action"] for entry in audit],
                                    "venn_abers": evidence.get("venn_abers"),
                                    "final_text": adk_models.final_text(events)}
    finally:
        await runner.close()
    return {"scenarios": outcomes, "marked": system.marked}


def run(argv: Optional[Sequence[str]] = None, *, reviewer: Optional[Reviewer] = None) -> dict[str, Any]:
    """Run the demo and return what happened (used by the tests)."""
    args = build_parser().parse_args(argv)
    evidence_provider = args.evidence_provider or args.provider
    # Both models are built before anything else, so a placeholder key stops the run here.
    model = adk_models.agent_model(args.provider, policy=prescreener_policy)
    backend = providers.evidence_backend(evidence_provider, mock_scorer=mock_eligibility_evidence)
    client = LocalCLIClient(backend, store=calibration.default_store(__file__, args.store),
                            sample_count=providers.sample_count(evidence_provider))

    display.banner("Google ADK: clinical-trial pre-screening with a Venn-Abers guard", "healthcare")
    print(f"agent model: {args.provider}; evidence model: {evidence_provider}")
    already, _ = client.calibration_status(ELIGIBILITY)
    sys.stdout.flush()  # calibration progress goes to stderr
    examples = calibration.load_jsonl("trial_screening.jsonl")
    profile = calibration.ensure_calibrated(client, [ELIGIBILITY], examples, recalibrate=args.recalibrate)[0]
    print(f"calibration: data/trial_screening.jsonl ({len(examples)} synthetic records)")
    print(f"profile: {profile.name}, {profile.method}, n={profile.n} (minimum {profile.minimum_n}), "
          f"{profile.status}, {'cached' if already and not args.recalibrate else 'calibrated now'}")
    print("rule: allow if p0 >= 0.85; block if p1 < 0.15; otherwise a coordinator decides")

    reviewer = reviewer or Reviewer(interactive=args.interactive, script=COORDINATOR_SCRIPT,
                                    role="research coordinator")
    result = asyncio.run(run_scenarios(client, model, reviewer))
    display.footer()
    result["profile"] = {"name": profile.name, "method": profile.method, "n": profile.n, "status": profile.status,
                         "calibrated_now": not already or args.recalibrate}
    return result


def main(argv: Optional[Sequence[str]] = None) -> int:
    run(argv)
    return 0


