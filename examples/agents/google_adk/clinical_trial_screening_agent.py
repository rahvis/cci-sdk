class ScreeningSystem:
    """Stand-in for the site's pre-screening records and trial-management system."""

    def __init__(self, records: Sequence[dict[str, Any]]) -> None:
        self.records = {r["patient_id"]: r for r in records}
        self.marked: list[dict[str, str]] = []

    def eligibility_context(self, args: dict[str, Any]) -> dict[str, Any]:
        """The guard's context for a proposed mark: the record, rendered like the calibration set.

        Only SYN-CKD-201 was calibrated, so a mark for another trial (or an
        unknown patient) raises here and the guard escalates.
        """
        if args.get("trial_id") != TRIAL_ID:
            raise ValueError(f"trial {args.get('trial_id')!r} has no calibration profile; only {TRIAL_ID} does")
        record = self.records.get(args.get("patient_id"))
        if record is None:
            raise ValueError(f"patient {args.get('patient_id')!r} has no pre-screening record")
        return screening_context(record)


def make_tools(system: ScreeningSystem):
    def get_prescreening_record(patient_id: str) -> dict:
        """Read a patient's pre-screening record: age, diagnoses, recent labs, medications, exclusions.

        Args:
            patient_id: The patient identifier, for example "P-6001".
        """
        record = system.records.get(patient_id)
        return screening_context(record)["patient"] if record else {"error": f"no record for {patient_id}"}

    def mark_eligible(patient_id: str, trial_id: str) -> dict:
        """Flag a patient as pre-screen eligible for a trial, for the study team to confirm at screening.

        Args:
            patient_id: The patient identifier.
            trial_id: The trial identifier, for example "SYN-CKD-201".
        """
        system.marked.append({"patient_id": patient_id, "trial_id": trial_id})
        return {"status": "marked_eligible", "patient_id": patient_id, "trial_id": trial_id}

    return get_prescreening_record, mark_eligible


